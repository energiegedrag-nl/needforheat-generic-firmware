"""Generate include/util/icons.hpp: 1-bit icons for the e-ink screen from Material Symbols (Apache-2.0).

Run from the repository root (needs cairosvg and Pillow, e.g. in a container):

    docker run --rm -v "$PWD":/src -w /src python:3.13-slim sh -c \
      "apt-get update -qq && apt-get install -y -qq libcairo2 >/dev/null && pip install -q cairosvg pillow && \
       python tools/icons/generate_icons.py"

The SVGs come from the npm package @material-symbols/svg-600 at a pinned version (filled, rounded, weight 600) and
are checked against the SHA-256 below. Each icon is drawn at 4x, scaled down with averaging and cut at 50%: cleaner
1-bit edges than drawing at the final size. To add an icon: add a line to ICONS, run once with --print-hashes, paste.
"""
import argparse
import hashlib
import io
import sys
import urllib.request
from pathlib import Path

PACKAGE = "@material-symbols/svg-600"
VERSION = "0.48.2"
STYLE = "rounded"
SIZE = 20  # pixels; fits the label row of a status tile (and of the main value)

# name on the device -> (Material Symbols file, SHA-256 of that file at VERSION)
ICONS = {
    "temperature": ("device_thermostat-fill", "756fa1f26df3556ef4c8ec84208ff1e41ed7ee8353b111eac4a91d2484deac07"),
    "humidity": ("humidity_percentage-fill", "f881ccafdc4b566fcdf513fc2baaac01612bccae65a68eea7877ba65d7fbd30f"),
    "person": ("person-fill", "a2f00526418b3b950cdb79d0101ab4fae2b7cf32956553c7d0e661add628c9ff"),
    "power": ("bolt-fill", "97960ec78c8fc9490557c3bd0e3ba0a1c2956e72f2d1e2c40fbc06bef321b456"),
    "gas": ("local_fire_department-fill", "7b81a5ba0f9f7378540f95e26473ee11aab032b6646a9c0bbcfca155502d6b1d"),
    "electricity_meter": ("electric_meter-fill", "ad2e5f58633c60505da8874d430b73ac88eb71b1fb4cbab3e2a2a0067a4d0fc8"),
    "gas_meter": ("gas_meter-fill", "f8b264026e55375add27cb3e31da60ee653ce5eea9603be54291b7ee4ad29819"),
}

OUT = Path("include/util/icons.hpp")


def fetch(file):
    url = f"https://unpkg.com/{PACKAGE}@{VERSION}/{STYLE}/{file}.svg"
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def rasterize(svg):
    import cairosvg
    from PIL import Image

    png = cairosvg.svg2png(bytestring=svg, output_width=SIZE * 4, output_height=SIZE * 4, background_color="white")
    image = Image.open(io.BytesIO(png)).convert("L").resize((SIZE, SIZE), Image.Resampling.BOX)
    return [[image.getpixel((x, y)) < 128 for x in range(SIZE)] for y in range(SIZE)]


def to_bytes(pixels):
    """Rows MSB first, padded to whole bytes (the format of LovyanGFX drawBitmap)."""
    out = []
    for row in pixels:
        for x0 in range(0, len(row), 8):
            byte = 0
            for i, on in enumerate(row[x0:x0 + 8]):
                if on:
                    byte |= 0x80 >> i
            out.append(byte)
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--print-hashes", action="store_true", help="print the SHA-256 of each file and stop")
    args = parser.parse_args()

    svgs = {}
    for name, (file, expected) in ICONS.items():
        data = fetch(file)
        digest = hashlib.sha256(data).hexdigest()
        if args.print_hashes:
            print(f'    "{name}": ("{file}", "{digest}"),')
            continue
        if digest != expected:
            sys.exit(f"{file}: SHA-256 {digest} does not match {expected}")
        svgs[name] = (file, data)
    if args.print_hashes:
        return

    lines = [
        "#pragma once",
        "// Generated by tools/icons/generate_icons.py; do not edit by hand.",
        f"// Icons: Material Symbols ({PACKAGE}@{VERSION}, {STYLE}, filled), Copyright Google LLC, Apache License 2.0",
        "// (tools/icons/LICENSE-material-symbols.txt). Drawn at 4x, scaled down and cut at 50% to 1 bit.",
        "",
        "#include <cstdint>",
        "#include <cstring>",
        "",
        "namespace Icons",
        "{",
        "\tstruct Icon",
        "\t{",
        "\t\tconst char *name;",
        "\t\tint width;",
        "\t\tint height;",
        "\t\tconst uint8_t *bits; // rows MSB first, padded to bytes (LovyanGFX drawBitmap)",
        "\t};",
        "",
    ]
    for name, (file, data) in svgs.items():
        pixels = rasterize(data)
        lines.append(f"\t// {file}")
        for row in pixels:
            lines.append("\t// " + "".join("#" if on else "." for on in row))
        values = ", ".join(f"0x{b:02x}" for b in to_bytes(pixels))
        lines.append(f"\tinline constexpr uint8_t {name.upper()}_BITS[] = {{{values}}};")
        lines.append("")
    lines.append("\tinline constexpr Icon ALL[] = {")
    for name in svgs:
        lines.append(f'\t\t{{"{name}", {SIZE}, {SIZE}, {name.upper()}_BITS}},')
    lines.append("\t};")
    lines += [
        "",
        "\t/** The icon with this name, or nullptr. */",
        "\tinline const Icon *Find(const char *name)",
        "\t{",
        "\t\tfor (const auto &icon : ALL)",
        "\t\t\tif (std::strcmp(icon.name, name) == 0)",
        "\t\t\t\treturn &icon;",
        "\t\treturn nullptr;",
        "\t}",
        "} // namespace Icons",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(svgs)} icons)")


if __name__ == "__main__":
    main()
